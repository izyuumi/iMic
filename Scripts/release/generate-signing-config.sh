#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TARGET="$ROOT/Config/Signing.xcconfig"

DEVELOPMENT_TEAM="${DEVELOPMENT_TEAM:?Missing DEVELOPMENT_TEAM}"
CODE_SIGN_IDENTITY="${CODE_SIGN_IDENTITY:?Missing CODE_SIGN_IDENTITY}"

cat <<EOF > "$TARGET"
DEVELOPMENT_TEAM = ${DEVELOPMENT_TEAM}
CODE_SIGN_STYLE = Automatic
CODE_SIGN_IDENTITY = ${CODE_SIGN_IDENTITY}

NOTARY_APPLE_ID = ${NOTARY_APPLE_ID:-}
NOTARY_TEAM_ID = ${NOTARY_TEAM_ID:-}
NOTARY_APP_PASSWORD = ${NOTARY_APP_PASSWORD:-}
NOTARY_PROFILE = ${NOTARY_PROFILE:-}
EOF

echo "Signing configuration generated at $TARGET"
